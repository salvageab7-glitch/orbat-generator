/// 用户消息的构造：把图片或文字包进 user message
String buildUserMessage({String? text, bool hasImage = false}) {
  final buffer = StringBuffer();
  if (hasImage) {
    buffer.writeln('请根据上面这张编制图图片，输出编制 JSON。逐框清点，不要遗漏。');
  }
  if (text != null && text.trim().isNotEmpty) {
    buffer.writeln('补充资料/要求：');
    buffer.writeln(text.trim());
  }
  if (buffer.isEmpty) {
    buffer.writeln('请把资料转成编制 JSON。');
  }
  return buffer.toString();
}
