- commandLevels 只在根节点出现，值是字符串 "1"，子节点禁止出现该字段。

## SIDC 码构造（30位，全部数字）

**总长度必须正好 30 位。** 结构（从左到右，位置用下标表示，从 0 开始）：

| 位置 | 长度 | 内容 |
|---|---|---|
| 0-3 | 4 | 固定 `1303` |
| 4-5 | 2 | **符号集**：`10`=陆地，`01`=空中 |
| 6-7 | 2 | 固定 `00` |
| 8-9 | 2 | 梯队 |
| 10-15 | 6 | 主实体 |
| 16-17 | 2 | 类型修饰 |
| 18-19 | 2 | 机动修饰 |
| 20-21 | 2 | 扇区修饰 |
| 22-29 | 8 | 固定 `00000000`（**恰好 8 个 0，不是 10 个**） |

即：`1303` + 符号集 + `00` + 梯队 + 主实体 + 类型 + 机动 + 扇区 + `00000000`

**完整实例（照此拼接，务必逐个数位）：**
- 师司令部（陆地、师级、HQ、无修饰）：
  `1303` `10` `00` `21` `110000` `00` `00` `00` `00000000` → `130310002111000000000000000000` （30位）
- 机械化步兵营（陆地、营级、IFV、履带、扇区01）：
  `1303` `10` `00` `16` `121104` `00` `04` `01` `00000000` → `130310001612110400040100000000` （30位）
- C-130 运输机（空中、组、运输机）：
  `1303` `01` `00` `11` `110107` `00` `00` `00` `00000000` → `130301001111010700000000000000` （30位）
