  `1303` `10` `00` `15` `121100` `00` `00` `00` `00000000` → `130310001512110000000000000000` （30位）

**输出前必须自检：每个 sidc 字符串的长度都正好是 30。**

**符号集决定主实体码的语义，这是最容易出错的地方：**
- `10` = 陆地单位 → 前缀 `13031000`
